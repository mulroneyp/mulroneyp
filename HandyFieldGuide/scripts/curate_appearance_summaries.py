def apply(path: Path, mapping: dict[str, str], *, is_list: bool) -> tuple[int, int]:
    data = json.loads(path.read_text(encoding="utf-8"))
    filled = 0
    blank = 0
    if is_list:
        species_lists = [data]
    else:
        species_lists = [cov["species"] for cov in data["coverages"]]

    for species_list in species_lists:
        for species in species_list:
            name = species["commonName"]
            if name not in mapping:
                raise SystemExit(f"Missing curated appearance line for {name!r} in {path.name}")
            text = mapping[name].strip()
            species["summary"] = text
            if text:
                filled += 1
            else:
                blank += 1

    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return filled, blank


def main() -> None:
    guide = RESOURCE / "guide.json"
    data = json.loads(guide.read_text(encoding="utf-8"))
    mv_names = {s["commonName"] for s in data["coverages"][0]["species"]}
    mel_names = {s["commonName"] for s in data["coverages"][1]["species"]}
    if mv_names != set(MONTEVERDE):
        raise SystemExit(f"Monteverde name mismatch: missing {mv_names-set(MONTEVERDE)} extra {set(MONTEVERDE)-mv_names}")
    if mel_names != set(MELBOURNE):
        raise SystemExit(f"Melbourne name mismatch: missing {mel_names-set(MELBOURNE)} extra {set(MELBOURNE)-mel_names}")

    # Apply per coverage so mappings stay separate.
    for cov in data["coverages"]:
        mapping = MONTEVERDE if cov["id"] == "monteverde" else MELBOURNE
        for species in cov["species"]:
            species["summary"] = mapping[species["commonName"]].strip()
    guide.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    supp_path = RESOURCE / "ebird_supplemental.json"
    supp = json.loads(supp_path.read_text(encoding="utf-8"))
    supp_names = {s["commonName"] for s in supp}
    if supp_names != set(SUPPLEMENTAL):
        raise SystemExit(
            f"Supplemental name mismatch: missing {supp_names-set(SUPPLEMENTAL)} "
            f"extra {set(SUPPLEMENTAL)-supp_names}"
        )
    for species in supp:
        species["summary"] = SUPPLEMENTAL[species["commonName"]].strip()
    supp_path.write_text(json.dumps(supp, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(
        "ok",
        f"monteverde={sum(1 for s in data['coverages'][0]['species'] if s['summary'])}/{len(data['coverages'][0]['species'])}",
        f"melbourne={sum(1 for s in data['coverages'][1]['species'] if s['summary'])}/{len(data['coverages'][1]['species'])}",
        f"supplemental={sum(1 for s in supp if s['summary'])}/{len(supp)}",
    )
    clay = next(s for s in data["coverages"][0]["species"] if s["commonName"] == "Clay-colored Thrush")
    print("Clay-colored Thrush summary:", clay["summary"])


if __name__ == "__main__":
    main()
